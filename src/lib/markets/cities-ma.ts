/** Not in the list: the customer types the locality in the address field. */
export const OTHER_CITY: City = { value: "Autre", fr: "Autre ville", ar: "مدينة أخرى", en: "Other city" };

const toCity = (major: boolean) => ([fr, ar, en]: Row): City => ({
  value: fr,
  fr,
  ar,
  ...(en ? { en } : {}),
  ...(major ? { major: true } : {}),
});

export const MA_CITIES: readonly City[] = [...MAJOR.map(toCity(true)), ...TOWNS.map(toCity(false)), OTHER_CITY];
