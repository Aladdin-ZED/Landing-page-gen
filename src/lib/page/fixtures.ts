/**
 * Page order of every section type, told as one story (the order form mid-page, after the first wave
 * of proof and the offers; the deep-dive blocks after it for the readers who keep scrolling):
 * promise → reassurance → pain → answer → product → numbers → (strip) → proof → offer → ORDER → how → see it →
 * brand → compare → details → voices → guarantee → last call → questions.
 */
