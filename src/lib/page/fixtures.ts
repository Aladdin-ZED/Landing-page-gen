/** The archetype's preferred variant that the section actually implements, else its first variant. */
function variantFor(type: string, archetype: Archetype): string {
  const def = getSection(type);
  const ids = def?.variants.map((v) => v.id) ?? [];
  const prefs = (THEME_SECTION_TYPES as readonly string[]).includes(type)
    ? getArchetype(archetype).preferredVariants[type as ThemeSectionType]
    : [];
  return prefs.find((p) => ids.includes(p)) ?? ids[0] ?? "default";
}

