export interface FixtureOptions {
  locale?: FixtureLocale;
  /** force another archetype (theme regenerated for it) */
  archetype?: Archetype;
  seed?: number;
  /** render time; countdowns are set relative to it */
  now?: string;
}

export interface Fixture {
  name: FixtureName;
  doc: PageDoc;
  store: StoreInfo;
  pageKey: string;
  slug: string;
}

function themeFor(spec: FixtureSpec, archetype: Archetype, seed: number): ThemeSpec {
  try {
    return themeFromProduct({ category: spec.category, palette: photo(spec.images[0]!).palette, archetype, seed });
  } catch {
    return { ...spec.fallbackTheme, archetype, seed };
  }
}

export function getFixture(name: FixtureName, opts: FixtureOptions = {}): Fixture {
  const spec: FixtureSpec = SPECS[name];
  const locale = opts.locale ?? spec.locale;
  const archetype = opts.archetype ?? spec.archetype;
  const seed = opts.seed ?? spec.seed;
  const nowMs = Date.parse(opts.now ?? new Date().toISOString());
  const tx = (l: L) => l[locale];
  const theme = themeFor(spec, archetype, seed);

  const product: PageDoc["product"] = {
    name: tx(spec.name),
    tagline: tx(spec.tagline),
    description: tx(spec.description),
    category: spec.category,
    images: spec.images.map((n) => ref(n)),
    price: spec.price,
    compareAt: spec.compareAt,
    sku: spec.sku,
    variants: spec.variants.map((g) => ({
      id: g.id,
      name: tx(g.name),
      kind: g.kind,
      perUnit: true,
      options: g.options.map((o) => ({ id: o.id, label: tx(o.label), soldOut: false, ...(o.swatch ? { swatch: o.swatch } : {}) })),
    })),
    rating: spec.rating,
  };

  const countdownEnd =
    spec.countdownHours && Number.isFinite(nowMs)
      ? new Date(Math.ceil((nowMs + spec.countdownHours * 3_600_000) / 60_000) * 60_000).toISOString()
      : undefined;

  const offers: PageDoc["offers"] = {
    bundles: spec.bundles.map((b) => ({
      id: b.id,
      qty: b.qty,
      price: b.price,
      ...(b.compareAt ? { compareAt: b.compareAt } : {}),
      ...(b.title ? { title: tx(b.title) } : {}),
      ...(b.subtitle ? { subtitle: tx(b.subtitle) } : {}),
      badge: b.badge ?? "none",
      freeShipping: true,
      ...(b.gift ? { gift: { label: tx(b.gift) } } : {}),
      ...(b.image ? { image: ref(b.image) } : {}),
      preselected: false,
    })),
    cardStyle: spec.cardStyle,
    showPerUnit: true,
    showSavings: spec.showSavings,
    shippingFee: 0,
    ...(spec.bump
      ? {
          orderBump: {
            enabled: true,
            title: tx(spec.bump.title),
            description: tx(spec.bump.description),
            price: spec.bump.price,
            ...(spec.bump.image ? { image: ref(spec.bump.image) } : {}),
          },
        }
      : {}),
    ...(spec.upsell
      ? {
          upsell: {
            enabled: true,
            title: tx(spec.upsell.title),
            description: tx(spec.upsell.description),
            price: spec.upsell.price,
            compareAt: spec.upsell.compareAt,
            windowMinutes: spec.upsell.minutes,
            ...(spec.upsell.image ? { image: ref(spec.upsell.image) } : {}),
          },
        }
      : {}),
    urgency: {
      ...(countdownEnd ? { countdownEnd } : {}),
      ...(spec.stockLeft !== undefined ? { stockLeft: spec.stockLeft } : {}),
    },
  };

  const basics = { locale, product, offers, theme };
  const defaultData = (type: string): Record<string, unknown> => {
    const def = getSection(type);
    if (!def) return {};
    try {
      const parsed = def.schema.safeParse(sectionDefaults(def, basics, type));
      return parsed.success && parsed.data && typeof parsed.data === "object" ? (parsed.data as Record<string, unknown>) : {};
    } catch {
      // a section whose defaults() throws keeps {} — validateDoc/renderPageBody repair or skip it
      return {};
    }
  };
  // section types registered after this layout was written still get exercised (inserted before the footer)
  const types = LAYOUT.filter((t) => !!getSection(t));
  for (const type of SECTION_TYPES) {
    if (types.includes(type)) continue;
    const at = types.indexOf("footer");
    types.splice(at < 0 ? types.length : at, 0, type);
  }
  // the generator's page rhythm, judged on this theme's real colors; transitions left to the renderer
  const plan = finishPlan(
    types.map((type) => ({ type, variant: variantFor(type, archetype) })),
    archetype,
    seed,
    themeTones(theme, locale),
  );
  const sections: PageDocInput["sections"] = plan.map((p) => ({
    id: p.type,
    type: p.type,
    variant: p.variant,
    bg: p.bg,
    divider: p.divider,
    spacing: p.spacing,
    hidden: false,
    data: defaultData(p.type),
  }));

  const input: PageDocInput = {
    v: 1,
    locale,
    market: "MA",
    currency: "MAD",
    product,
    offers,
    form: {
      city: "select",
      address: "required",
      note: "optional",
      email: "hidden",
      phoneCountry: "MA",
      whatsapp: { enabled: true, number: spec.store.whatsapp },
    },
    theme,
    sections,
    seo: { title: tx(spec.seo.title), description: tx(spec.seo.description), noindex: true },
    tracking: {},
    thankYou: { showTimeline: true },
  };

  return {
    name,
    doc: PageDoc.parse(input),
    store: { ...spec.store, country: "MA" },
    pageKey: `pk_fixture_${name}`,
    slug: name,
  };
}
