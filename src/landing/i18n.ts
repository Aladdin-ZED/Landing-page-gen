const DICTS: Partial<Record<Locale, Dict>> = { fr, ar, en };

export const UI_LOCALES_COMPLETE: Locale[] = ["ar", "fr", "en"];

function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/**
 * The plural forms of `key` for `locale` (createT's fallback chain), keeping `other` plus only the
 * forms that differ from it; null for a plain string. Lets the runtime re-pick a label while a live
 * number changes (the countdown's day label), with the same Intl.PluralRules categories as t().
 */
export function pluralForms(locale: Locale, key: UiKey): Record<string, string> | null {
  const entry: Entry | undefined = (DICTS[locale] ?? en)[key] ?? en[key] ?? fr[key];
  if (entry === undefined || typeof entry === "string") return null;
  const out: Record<string, string> = { other: entry.other };
  for (const [cat, form] of Object.entries(entry)) if (typeof form === "string" && form !== entry.other) out[cat] = form;
  return out;
}

/** Create the t() function for a locale. Falls back to English, then French. */
export function createT(locale: Locale) {
  const dict = DICTS[locale] ?? en;
  const rules = new Intl.PluralRules(locale);
  return (key: UiKey, vars?: Record<string, string | number>): string => {
    let entry: Entry | undefined = dict[key] ?? en[key] ?? fr[key];
    if (entry === undefined) return key;
    if (typeof entry !== "string") {
      const n = Number(vars?.n ?? 0);
      const cat = rules.select(n);
      entry = entry[cat] ?? entry.other;
    }
    return interpolate(entry, vars);
  };
}
